// Usage: tsx scripts/embed-templates.ts          (writes worker/src/static/templates.gen.ts)
//        tsx scripts/embed-templates.ts --check  (exit 1 if the committed file is out of date)
// Embeds templates/tpl-*/{index.html,theme.css} and templates/_shared/{render.js,base.css} as string exports,
// and worker/src/static/package/{package.html,package.js,package.css} (the /package/:siteId page),
// so the Worker serves /d/:siteId and /package/:siteId without wrangler Text rules. Runs in the worker's pretest and predeploy.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
export const TEMPLATES_DIR = resolve(HERE, '../templates');
export const OUT_FILE = resolve(HERE, '../worker/src/static/templates.gen.ts');
export const PACKAGE_DIR = resolve(HERE, '../worker/src/static/package');

const read = (p: string) => readFileSync(p, 'utf8');

export function generate(dir = TEMPLATES_DIR, pkgDir = PACKAGE_DIR): string {
  const tpls = readdirSync(dir).filter((n) => n.startsWith('tpl-') && statSync(join(dir, n)).isDirectory()).sort();
  const lines = [
    '// GENERATED by scripts/embed-templates.ts from templates/ and worker/src/static/package/ — do not edit. Regenerate: pnpm -F @sme/worker embed',
    "import type { TemplateId } from '@sme/schema';",
    '',
    'export const SHARED: { renderJs: string; baseCss: string } = {',
    `  renderJs: ${JSON.stringify(read(join(dir, '_shared/render.js')))},`,
    `  baseCss: ${JSON.stringify(read(join(dir, '_shared/base.css')))},`,
    '};',
    '',
    'export const TEMPLATE_FILES: Record<TemplateId, { html: string; theme: string }> = {',
    ...tpls.map((t) => `  ${JSON.stringify(t)}: { html: ${JSON.stringify(read(join(dir, t, 'index.html')))}, theme: ${JSON.stringify(read(join(dir, t, 'theme.css')))} },`),
    '};',
    '',
    'export const PACKAGE_FILES: { html: string; js: string; css: string } = {',
    `  html: ${JSON.stringify(read(join(pkgDir, 'package.html')))},`,
    `  js: ${JSON.stringify(read(join(pkgDir, 'package.js')))},`,
    `  css: ${JSON.stringify(read(join(pkgDir, 'package.css')))},`,
    '};',
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = generate();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = read(OUT_FILE); } catch { /* missing */ }
    if (cur !== out) { console.error('templates.gen.ts is out of date: run pnpm -F @sme/worker embed'); process.exit(1); }
  } else {
    mkdirSync(dirname(OUT_FILE), { recursive: true });
    writeFileSync(OUT_FILE, out);
  }
}
